def _strands(runs, color, w=0.45, op=0.6):
    return [path(smooth(r, closed=False), stroke=color, w=w, op=op) for r in runs]


def _hair(key, label, inner, outer, tone, art, tab_x, tab_y):
    """머리 한 조각. inner=얼굴 창, outer=턱 옆에서 정수리로 돌아오는 바깥 윤곽."""
    p = Piece(key, label, "hair", tags=["hair"])
    shape = sym(inner + outer)
    d = smooth(shape)

    # 바깥 윤곽만 여백 있는 오림선. 열린 경로라 fill 을 끈다.
    outer_full = outer + mirror(outer)[1:]
    p.cut(smooth(outer_full, closed=False), shape, clip=False, fill=False)
    # 얼굴 창은 밀착 오림선
    inner_full = mirror(inner) + inner[1:]
    p.tight(smooth(inner_full, closed=False))
    p.clip(d)

    t = S.TAB["hair_crown"]
    for s in (-1, 1):
        p.tab(s * tab_x, tab_y, t["w"], t["h"], "up", name="정수리")

    lo, dk, hi = S.HAIR[tone]
    p.add_defs(lg(p.g("h"), [(0.0, hi), (0.38, lo), (1.0, dk)]))
    if not p.use_art():
        p.art(path(d, fill=f"url(#{p.g('h')})", c=True))
        p.art(*art(d, lo, dk, hi))
        p.art(rim(d, dk, w=2.4, op=0.4))
        p.art(*volume(p, d, top=0.2, bottom=0.14, side=0.12, tone=dk))
        p.art(path(d, stroke=S.INK, w=0.34))
    return p


